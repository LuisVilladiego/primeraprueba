def q(es, en, es_opts, en_opts, correct, es_why, en_why):
    return {
        "question": {"es": es, "en": en},
        "options": {"es": es_opts, "en": en_opts},
        "correct": correct,
        "explanation": {"es": es_why, "en": en_why},
    }

def lesson(slug, es_t, en_t, es_d, en_d, es_why, en_why, es_c, en_c, es_cmd, en_cmd, es_p, en_p, quiz, warning=None):
    item = {
        "slug": slug,
        "title": {"es": es_t, "en": en_t},
        "description": {"es": es_d, "en": en_d},
        "why": {"es": es_why, "en": en_why},
        "concept": {"es": es_c, "en": en_c},
        "commands": {"es": es_cmd, "en": en_cmd},
        "practice": {"es": es_p, "en": en_p},
        "quiz": quiz,
    }
    if warning:
        item["warning"] = {"es": warning[0], "en": warning[1]}
    return item

